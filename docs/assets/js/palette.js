/** パレットをCSV文字列にする。スプレッドシートで色見本を作るために使う。 */
export function paletteToCsv() {
  const header = 'id,color,group,shade,r,g,b';
  const lines = PALETTE.map((swatch) => {
    const [r, g, b] = [1, 3, 5].map((i) => parseInt(swatch.hex.slice(i, i + 2), 16));
    return [swatch.id, swatch.hex, swatch.group, swatch.shade, r, g, b].join(',');
  });
  return [header, ...lines].join('\r\n') + '\r\n';
}
