-- LoadSym: クリアランス（機材どうし・機材と壁の隙間）をレイアウトごとの設定にする。
--
-- これまでクリアランスは 10mm 固定だった。しかし実際にどれだけ隙間を確保するかは
-- 現場によって変わる（詰めて積みたい日もあれば、養生や積み下ろしの都合で余裕を
-- 取りたい日もある）。どこまで確保するかはユーザーに委ねたい。
--
-- 値はレイアウトごとに持たせる。全体設定にすると、5mm で組んだ図を 10mm 設定の
-- 人が開いたときに配置の意図が変わってしまい、図の再現性が壊れるため。
--
-- 既定値は 5mm。従来の 10mm は実作業に対して余裕を取りすぎで、荷台を使い切れない
-- 場面があった。範囲は 1〜10mm とする。1mm を下限にするのは、0mm（＝機材どうしが
-- 完全に接する）を許すと手や吊りベルトが入らず、実際には積めない図ができるため。
--
-- 既存のレイアウトには 5mm が入る。クリアランスはスナップの吸着先を決める値で
-- あって、保存済みの座標を動かすものではないため、開き直しても図は変わらない。

alter table public.layouts
  add column clearance_mm smallint not null default 5
    check (clearance_mm between 1 and 10);

comment on column public.layouts.clearance_mm is
  '機材どうし・機材と壁のクリアランス(mm)。スナップと押し出しの目標値。1〜10、既定5。';
